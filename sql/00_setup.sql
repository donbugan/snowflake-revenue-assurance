USE ROLE ACCOUNTADMIN;

-- Compute: smallest warehouse, suspends after 60s idle
CREATE WAREHOUSE IF NOT EXISTS RA_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

-- Cost guardrail: notify at 80%, suspend at 100% of 5 credits a month
CREATE OR REPLACE RESOURCE MONITOR RA_RM WITH CREDIT_QUOTA = 5 FREQUENCY = MONTHLY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 80 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND;
ALTER WAREHOUSE RA_WH SET RESOURCE_MONITOR = RA_RM;

-- Storage layers
CREATE DATABASE IF NOT EXISTS RA_DEMO;
CREATE SCHEMA IF NOT EXISTS RA_DEMO.BRONZE;   -- raw files, all text, load metadata
CREATE SCHEMA IF NOT EXISTS RA_DEMO.SILVER;   -- typed, cleaned, matched
CREATE SCHEMA IF NOT EXISTS RA_DEMO.GOLD;     -- golden thread and exceptions

-- Roles: engineer builds everything, analyst reads GOLD only
CREATE ROLE IF NOT EXISTS RA_ENGINEER;
CREATE ROLE IF NOT EXISTS RA_ANALYST;
GRANT ROLE RA_ANALYST  TO ROLE RA_ENGINEER;     -- engineer inherits analyst
GRANT ROLE RA_ENGINEER TO ROLE SYSADMIN;
SET me = CURRENT_USER();
GRANT ROLE RA_ENGINEER TO USER IDENTIFIER($me);
GRANT ROLE RA_ANALYST  TO USER IDENTIFIER($me);

GRANT USAGE ON WAREHOUSE RA_WH TO ROLE RA_ANALYST;
GRANT OPERATE ON WAREHOUSE RA_WH TO ROLE RA_ENGINEER;
GRANT USAGE ON DATABASE RA_DEMO TO ROLE RA_ANALYST;
GRANT ALL ON DATABASE RA_DEMO TO ROLE RA_ENGINEER;
GRANT ALL ON SCHEMA RA_DEMO.BRONZE TO ROLE RA_ENGINEER;
GRANT ALL ON SCHEMA RA_DEMO.SILVER TO ROLE RA_ENGINEER;
GRANT ALL ON SCHEMA RA_DEMO.GOLD   TO ROLE RA_ENGINEER;
GRANT USAGE ON SCHEMA RA_DEMO.GOLD TO ROLE RA_ANALYST;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RA_DEMO.GOLD TO ROLE RA_ANALYST;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA RA_DEMO.GOLD TO ROLE RA_ANALYST;

-- Landing: internal stage and CSV format
USE ROLE RA_ENGINEER;
USE WAREHOUSE RA_WH;
USE SCHEMA RA_DEMO.BRONZE;
CREATE OR REPLACE FILE FORMAT CSV_FF TYPE = CSV SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"' NULL_IF = ('') EMPTY_FIELD_AS_NULL = TRUE TRIM_SPACE = TRUE;
CREATE OR REPLACE STAGE RA_STAGE FILE_FORMAT = CSV_FF;

